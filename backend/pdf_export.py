"""Server-side PDF rendering of a final research report.

Uses fpdf2 (lightweight, pure-Python) with the built-in Helvetica core
fonts. Core fonts are Latin-1; text is sanitized through a conservative
transliteration table (smart quotes, dashes, ellipsis) plus a final
Latin-1 replacement pass, so no raw bytes ever break the PDF encoder.

Rendering is deliberately deterministic and injection-safe: the markdown
is converted to a small whitelist of text operations (headings, bullets,
code lines, paragraphs). No HTML, no markup passthrough, no external
resources, no file writes.
"""

from __future__ import annotations

import re
from datetime import datetime, timezone

from agents.schemas import Report

# Deterministic transliterations applied BEFORE Latin-1 encoding.
_TRANSLATIONS = {
    "\u2018": "'",   # left single quote
    "\u2019": "'",   # right single quote
    "\u201c": '"',   # left double quote
    "\u201d": '"',   # right double quote
    "\u2013": "-",   # en dash
    "\u2014": "--",  # em dash
    "\u2026": "...", # ellipsis
    "\u2022": "-",   # bullet
    "\u00a0": " ",   # nbsp
    "\u20b9": "Rs.", # rupee sign
}

_HEADING_SIZES = {1: 16, 2: 13, 3: 12}


def sanitize_for_pdf(text: str) -> str:
    """Transliterate common Unicode, then force Latin-1 with replacement."""
    for src, dst in _TRANSLATIONS.items():
        text = text.replace(src, dst)
    return text.encode("latin-1", "replace").decode("latin-1")


def _strip_inline(markdown: str) -> str:
    """Remove inline markdown emphasis/links/code, keep citations [N]."""
    text = re.sub(r"!\[([^\]]*)\]\(([^)]*)\)", r"\1", markdown)
    text = re.sub(r"\[([^\]]*)\]\(([^)]*)\)", r"\1 (\2)", text)
    text = re.sub(r"\*\*([^*]+)\*\*", r"\1", text)
    text = re.sub(r"\*([^*]+)\*", r"\1", text)
    text = text.replace("`", "")
    return text


def slugify(text: str) -> str:
    slug = re.sub(r"[^A-Za-z0-9]+", "-", text).strip("-").lower()
    return (slug or "agentdesk-report")[:60]


def render_report_pdf(
    report: Report,
    query: str = "",
    retrieval_mode: str = "both",
    final_status: str = "",
    generated_at: datetime | None = None,
) -> bytes:
    """Render a Report to PDF bytes.

    Raises ValueError when the report has no title and no content.
    """
    if not report.title.strip() and not report.markdown.strip():
        raise ValueError("Report has no content to render.")

    from fpdf import FPDF
    from fpdf.enums import XPos, YPos

    pdf = FPDF(format="A4")
    pdf.set_auto_page_break(auto=True, margin=18)
    pdf.set_margins(18, 18, 18)
    pdf.add_page()

    def line(text: str = ""):
        # Explicit cursor reset: fpdf2's multi_cell default leaves the
        # cursor at the right margin, which would break the next cell.
        pdf.multi_cell(
            0, 5, sanitize_for_pdf(text),
            new_x=XPos.LMARGIN, new_y=YPos.NEXT,
        )

    # Header / metadata block
    pdf.set_font("helvetica", "B", 18)
    if report.title.strip():
        line(report.title.strip())
        pdf.ln(2)
    pdf.set_font("helvetica", "", 9)
    pdf.set_text_color(90)
    stamp = (generated_at or datetime.now(timezone.utc)).strftime(
        "%Y-%m-%d %H:%M UTC"
    )
    meta_bits = [f"Generated by AgentDesk - {stamp}"]
    if query.strip():
        meta_bits.append(f"Research goal: {sanitize_for_pdf(query.strip())}")
    if retrieval_mode:
        meta_bits.append(f"Retrieval mode: {retrieval_mode}")
    if final_status:
        meta_bits.append(f"Status: {final_status}")
    for bit in meta_bits:
        line(bit)
    pdf.set_text_color(0)
    pdf.ln(4)

    # Body
    in_code = False
    for raw_line in report.markdown.split("\n"):
        stripped = raw_line.strip()

        if stripped.startswith("```"):
            in_code = not in_code
            continue
        if in_code:
            pdf.set_font("courier", "", 9)
            line(raw_line)
            pdf.set_font("helvetica", "", 10)
            continue

        if not stripped:
            pdf.ln(2)
            continue

        heading = re.match(r"^(#{1,3})\s+(.*)$", stripped)
        if heading:
            level = len(heading.group(1))
            pdf.set_font("helvetica", "B", _HEADING_SIZES[level])
            pdf.ln(2)
            line(_strip_inline(heading.group(2).strip()))
            pdf.set_font("helvetica", "", 10)
            pdf.ln(1)
            continue

        bullet = re.match(r"^[-*]\s+(.*)$", stripped)
        numbered = re.match(r"^(\d+[.)])\s+(.*)$", stripped)
        if bullet:
            pdf.set_x(pdf.l_margin + 4)
            line(f"- {_strip_inline(bullet.group(1))}")
            continue
        if numbered:
            pdf.set_x(pdf.l_margin + 4)
            line(f"{numbered.group(1)} {_strip_inline(numbered.group(2))}")
            continue

        # Tables: render rows as plain text with pipes preserved.
        line(_strip_inline(stripped))

    pdf.ln(4)
    pdf.set_font("helvetica", "I", 8)
    pdf.set_text_color(120)
    line(
        "Citation numbers refer to the numbered evidence sources gathered "
        "during this run. This document was generated automatically from "
        "retrieved evidence."
    )

    return bytes(pdf.output())
